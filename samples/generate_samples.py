    c.setFont("Helvetica-Bold", 16)
    c.drawString(1 * inch, height - 1 * inch, "Springfield Family Medicine \u2014 Referral Cover Letter")
    c.setFont("Helvetica", 10)
    c.drawString(1 * inch, height - 1.3 * inch, "123 Synthetic Ave, Springfield, ST 00000")
    c.drawString(1 * inch, height - 1.48 * inch, "Referring provider: Dr. Sam Synthetica, MD (synthetic)")
