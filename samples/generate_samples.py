def _load_font(size: int) -> ImageFont.FreeTypeFont:
    for candidate in (
        "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
        "DejaVuSans.ttf",
    ):
        try:
            return ImageFont.truetype(candidate, size)
        except OSError:
            continue
    return ImageFont.load_default()


def _draw_image_banner(draw: ImageDraw.ImageDraw, width: int) -> None:
    draw.rectangle([(0, 0), (width, 40)], fill=(176, 0, 32))
    font = _load_font(14)
    draw.text((width / 2, 20), BANNER_TEXT, fill="white", anchor="mm", font=font)


def make_fax_coversheet_png(path: Path) -> None:
    """Fax Systems: a classic fax cover sheet transmission page."""
    width, height = 1275, 1650  # 8.5x11in @ 150dpi
    image = Image.new("RGB", (width, height), "white")
    draw = ImageDraw.Draw(image)
    _draw_image_banner(draw, width)

    title_font = _load_font(30)
    label_font = _load_font(16)
    value_font = _load_font(16)
    small_font = _load_font(12)

    draw.text((80, 80), "FAX COVER SHEET", fill="black", font=title_font)
    draw.line([(80, 130), (width - 80, 130)], fill="black", width=2)

    fields = {
        "To": "HomeCare Referral Intake Fax Line \u2014 (000) 555-0102",
        "From": "Riverside Clinic Referrals Desk (synthetic)",
        "Fax number": "(000) 555-0199",
        "Date": "2030-01-18",
        "Pages": "2 (including this cover sheet)",
        "Re": "Synthetic specialist consultation referral",
    }
    y = 170
    for label, value in fields.items():
        draw.text((80, y), f"{label}:", fill="black", font=label_font)
        draw.text((320, y), value, fill="black", font=value_font)
        y += 40

    y += 20
    draw.line([(80, y), (width - 80, y)], fill="black", width=1)
    y += 30
    draw.text((80, y), "Patient details (synthetic):", fill="black", font=label_font)
    y += 40
    patient_fields = {
        "Patient": f"{PATIENT['name']} (synthetic)",
        "Date of birth": PATIENT["dob"],
        "MRN": PATIENT["mrn"],
        "Priority": "Expedited",
        "Requested date": "2030-01-22",
    }
    for label, value in patient_fields.items():
        draw.text((80, y), f"{label}:", fill="black", font=label_font)
        draw.text((320, y), value, fill="black", font=value_font)
        y += 36

    y += 30
    draw.text(
        (80, y),
        "Generated demonstration referral transmitted by fax; contains no personal data.",
        fill="black",
        font=small_font,
    )

    draw.text(
        (80, height - 60),
        "Generated by samples/generate_samples.py for workshop use.",
        fill=(90, 90, 90),
        font=small_font,
    )
    image.save(path, format="PNG")


