"""Generate the synthetic sample referral documents in this folder.

Regenerate with:

    python3 -m venv .venv && .venv/bin/pip install reportlab pillow
    .venv/bin/python samples/generate_samples.py

Every document produced here is entirely synthetic: no real patient,
provider, or organization is represented. Filenames follow the
`synthetic-<description>.<ext>` convention required by
`api/referral/guardrails.py` so they can be uploaded to the running API
as-is (with the `X-Data-Classification: synthetic` header).
"""

from __future__ import annotations

from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import LETTER
from reportlab.lib.units import inch
from reportlab.pdfgen import canvas
from PIL import Image, ImageDraw, ImageFont

OUT_DIR = Path(__file__).parent
BANNER_TEXT = "SYNTHETIC TEST DATA \u2014 NOT REAL PHI \u2014 GENERATED FOR WORKSHOP USE ONLY"

PATIENT = {
    "name": "Pat Testerson",
    "dob": "2030-01-01",
    "mrn": "SYN-000123",
}


def _draw_banner(c: canvas.Canvas, width: float, height: float) -> None:
    c.setFillColor(colors.HexColor("#B00020"))
    c.rect(0, height - 0.45 * inch, width, 0.45 * inch, fill=1, stroke=0)
    c.setFillColor(colors.white)
    c.setFont("Helvetica-Bold", 10)
    c.drawCentredString(width / 2, height - 0.3 * inch, BANNER_TEXT)
    c.setFillColor(colors.black)


def _draw_field_block(c: canvas.Canvas, x: float, y: float, fields: dict[str, str]) -> float:
    c.setFont("Helvetica-Bold", 11)
    for label, value in fields.items():
        c.setFont("Helvetica-Bold", 10)
        c.drawString(x, y, f"{label}:")
        c.setFont("Helvetica", 10)
        c.drawString(x + 1.6 * inch, y, value)
        y -= 0.24 * inch
    return y


def make_referral_portal_pdf(path: Path) -> None:
    """Referral Portals: a structured web-form submission confirmation."""
    c = canvas.Canvas(str(path), pagesize=LETTER)
    width, height = LETTER
    _draw_banner(c, width, height)

    c.setFont("Helvetica-Bold", 16)
    c.drawString(1 * inch, height - 1 * inch, "Online Referral Portal \u2014 Submission Confirmation")
    c.setFont("Helvetica", 10)
    c.drawString(1 * inch, height - 1.25 * inch, "Portal: HomeCare Connect Referral Portal")
    c.drawString(1 * inch, height - 1.45 * inch, "Submission ID: PORTAL-SYN-90210")

    y = height - 1.9 * inch
    y = _draw_field_block(
        c,
        1 * inch,
        y,
        {
            "Patient": f"{PATIENT['name']} (synthetic)",
            "Date of birth": PATIENT["dob"],
            "MRN": PATIENT["mrn"],
            "Referral type": "Synthetic specialist consultation",
            "Priority": "Routine",
            "Service requested": "Synthetic care navigation",
            "Requested date": "2030-01-15",
        },
    )

    c.setFont("Helvetica-Bold", 10)
    c.drawString(1 * inch, y - 0.15 * inch, "Summary:")
    c.setFont("Helvetica", 10)
    c.drawString(
        1 * inch,
        y - 0.4 * inch,
        "Generated demonstration referral submitted via the self-service portal;",
    )
    c.drawString(1 * inch, y - 0.6 * inch, "contains no personal data.")

    c.setFont("Helvetica-Oblique", 8)
    c.drawString(1 * inch, 0.75 * inch, "Generated by samples/generate_samples.py for workshop use.")
    c.save()


